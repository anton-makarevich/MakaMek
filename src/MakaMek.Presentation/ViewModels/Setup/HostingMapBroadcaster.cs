using System.ComponentModel;
using System.Reactive.Linq;
using System.Reactive.Subjects;
using Sanet.Localization;
using Sanet.MakaMek.Core.Models.Game;
using Sanet.MakaMek.Map.Models;
using Sanet.MVVM.Core.Services;

namespace Sanet.MakaMek.Presentation.ViewModels.Setup;

/// <summary>
/// Broadcasts the lobby map once map reselection settles, and starts the hosted game: locks the relay
/// room, applies the map, triggers the phase transition and navigates to the battle map. Kept out of
/// the hosting view model so it does not depend on the map model or the battle-map screen.
/// </summary>
public sealed class HostingMapBroadcaster : IDisposable
{
    private readonly IGameManager _gameManager;
    private readonly MapConfigViewModel _mapConfig;
    private readonly ILocalizationService _localizationService;
    private readonly Subject<BattleMap> _mapChanges = new();
    private IDisposable? _mapChangeSubscription;

    public HostingMapBroadcaster(
        IGameManager gameManager,
        MapConfigViewModel mapConfig,
        ILocalizationService localizationService)
    {
        _gameManager = gameManager;
        _mapConfig = mapConfig;
        _localizationService = localizationService;
    }

    private void OnMapConfigPropertyChanged(object? sender, PropertyChangedEventArgs e)
    {
        if (e.PropertyName != nameof(MapConfigViewModel.Map)) return;
        var map = _mapConfig.Map;
        if (map == null) return;
        _mapChanges.OnNext(map);
    }

    /// <summary>
    /// Broadcast the lobby map to the server once reselection settles (debounced).
    /// SetBattleMap only broadcasts the map; the phase transition is triggered explicitly through
    /// <see cref="StartGameAsync"/> when the host starts the game.
    /// </summary>
    public void Subscribe()
    {
        Unsubscribe();
        _mapConfig.PropertyChanged += OnMapConfigPropertyChanged;
        _mapChangeSubscription = _mapChanges
            .Throttle(TimeSpan.FromSeconds(5))
            .Subscribe(map => _gameManager.SetBattleMap(map));
    }

    public void Unsubscribe()
    {
        _mapConfig.PropertyChanged -= OnMapConfigPropertyChanged;
        _mapChangeSubscription?.Dispose();
        _mapChangeSubscription = null;
    }

    /// <summary>
    /// Starts the hosted game and navigates to it. <see cref="HostingStartOutcome.Started"/> is
    /// <c>false</c> when there is no map yet or the online room could not be locked.
    /// </summary>
    public async Task<HostingStartOutcome> StartGameAsync(
        INavigationService navigationService,
        bool isOnlineMode,
        ClientGame? localGame)
    {
        if (_mapConfig.Map == null) return HostingStartOutcome.NotStarted(null);
        // Use the map generated by MapConfigViewModel to ensure preview and game map are identical
        var map = _mapConfig.Map;

        // Lock the online relay room now that the lobby is transitioning to deployment;
        // LAN hosting has no relay room to lock.
        if (isOnlineMode)
        {
            var lockSucceeded = await _gameManager.LockOnlineRoom();
            if (!lockSucceeded)
            {
                return HostingStartOutcome.NotStarted(_gameManager.OnlineError?.Message
                    ?? _localizationService.GetString("Hosting_Failed"));
            }
        }

        // Set BattleMap on GameManager/ServerGame (propagates to clients via the command system)
        _gameManager.SetBattleMap(map);

        // Cancel any pending debounced map re-broadcast so no stale SetBattleMapCommand
        // can be published after the Start → Deployment transition below.
        Unsubscribe();

        // Explicitly trigger the Start → Deployment transition now that the map is set
        // and all players are ready. SetBattleMap no longer transitions on its own.
        _gameManager.TryStartGame();

        // Host Client for local player(s)
        var battleMapViewModel = await navigationService.GetNewViewModelAsync<BattleMapViewModel>();
        if (battleMapViewModel == null)
        {
            throw new InvalidOperationException("BattleMapViewModel is not registered");
        }
        battleMapViewModel.Game = localGame;

        // Navigate to BattleMap view
        await navigationService.NavigateToViewModelAsync(battleMapViewModel);
        return HostingStartOutcome.StartedGame();
    }

    public void Dispose()
    {
        Unsubscribe();
        _mapChanges.Dispose();
    }
}

/// <summary>
/// The result of trying to start the hosted game.
/// </summary>
public readonly record struct HostingStartOutcome(bool Started, string? Error)
{
    public static HostingStartOutcome StartedGame() => new(true, null);
    public static HostingStartOutcome NotStarted(string? error) => new(false, error);
}
